-- ============================================================================
-- V1: tools 表 —— 工具元数据
-- ----------------------------------------------------------------------------
-- 字段说明：
--   id          主键（IDENTITY，兼容 PostgreSQL 与 H2 MODE=PostgreSQL）
--   slug        URL 友好标识，全局唯一
--   name        工具显示名称
--   category    分类：developer / image
--   keywords    关键词，逗号分隔，用于搜索匹配
--   description 工具描述
--   enabled     启用标志，默认 true
--   use_count   使用次数冗余字段（避免实时 COUNT 聚合）
--   like_count  点赞次数冗余字段（避免实时 COUNT 聚合）
--   created_at  创建时间（JPA @CreatedDate 审计填充）
--   updated_at  更新时间（JPA @LastModifiedDate 审计填充）
--
-- 索引：
--   uk_tools_slug                  slug 唯一索引
--   idx_tools_category_use_count   (category, use_count) 复合索引，支持分类热门排序
-- ============================================================================

CREATE TABLE tools (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(100)  NOT NULL,
    name        VARCHAR(100)  NOT NULL,
    category    VARCHAR(50)   NOT NULL,
    keywords    VARCHAR(500),
    description VARCHAR(1000),
    enabled     BOOLEAN       NOT NULL DEFAULT TRUE,
    use_count   BIGINT        NOT NULL DEFAULT 0,
    like_count  BIGINT        NOT NULL DEFAULT 0,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- slug 唯一索引
CREATE UNIQUE INDEX uk_tools_slug ON tools (slug);

-- (category, use_count) 复合索引：支持分类页按热门（use_count 降序）排序
CREATE INDEX idx_tools_category_use_count ON tools (category, use_count);
