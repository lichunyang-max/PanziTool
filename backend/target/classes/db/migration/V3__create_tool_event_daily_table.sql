-- ============================================================================
-- V3: tool_event_daily 表 —— 按天聚合统计
-- ----------------------------------------------------------------------------
-- 字段说明：
--   id          主键（IDENTITY）
--   tool_id     外键 → tools.id
--   event_date  事件日期
--   event_type  事件类型：page_view / tool_use / copy / download
--   count       当天该事件计数
--   created_at  创建时间（JPA @CreatedDate 审计填充）
--   updated_at  更新时间（JPA @LastModifiedDate 审计填充）
--
-- 约束：
--   uk_tool_event_daily_tool_date_type  (tool_id, event_date, event_type) 唯一约束
--     防止同一工具同一天同一事件类型重复聚合
-- ============================================================================

CREATE TABLE tool_event_daily (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id     BIGINT       NOT NULL,
    event_date  DATE         NOT NULL,
    event_type  VARCHAR(30)  NOT NULL,
    count       BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tool_event_daily_tool_date_type
        UNIQUE (tool_id, event_date, event_type),
    CONSTRAINT fk_tool_event_daily_tool
        FOREIGN KEY (tool_id) REFERENCES tools (id)
);
