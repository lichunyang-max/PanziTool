-- ============================================================================
-- V9: 重置工具使用次数和点赞次数为 0
-- ----------------------------------------------------------------------------
-- 问题描述：V6 种子数据中 use_count / like_count 设置了较大的虚构初始值（如 12300），
--           导致首页热门工具展示的使用次数远大于真实用户行为产生的数据。
--
-- 修复方案：将所有工具的 use_count 和 like_count 重置为 0，
--           让计数从真实用户行为开始累积。
-- ============================================================================

UPDATE tools SET use_count = 0, like_count = 0, updated_at = CURRENT_TIMESTAMP;
